// Regenerates shared/fixtures/quality-cases.json: transcript-quality cases shared by the Node tests
// and the iPhone/iPad port (TranscriptQuality.swift), so both platforms give the same verdicts.
import { writeFile } from 'node:fs/promises';
import { auditTranscript, piecesFor } from '../companion/transcript-quality.mjs';
import { incident, lecture } from '../tests/fixtures/lecture.mjs';

const kinds = report => [...new Set(report.findings.map(f => f.kind))].sort();
const make = (name, segments, options) => {
  const report = auditTranscript(segments, options);
  return { name, options, segments, expected: { status: report.status, kinds: kinds(report) } };
};
const definition = 'The inguinal ligament is formed by the external oblique aponeurosis.';
const cases = [
  make('incident-971-repeats', incident(), { duration: 2514 }),
  make('normal-lecture', lecture({ to: 900, seed: 1 }), { duration: 900 }),
  make('lecturer-emphasis', [...lecture({ to: 600, seed: 3 }), { start: 120.1, end: 125, text: `${definition} ${definition}` }, { start: 240.3, end: 245, text: definition }, { start: 30.5, end: 31, text: 'Okay? Okay?' }].sort((a, b) => a.start - b.start), { duration: 600 }),
  make('zero-length-segments', [...lecture({ to: 600, seed: 11 }), ...Array.from({ length: 6 }, (_, i) => ({ start: 444 + i * 0.1, end: 444.1 + i * 0.1, text: 'And here in the midline, the aponeurosis of the external oblique muscle.' }))].sort((a, b) => a.start - b.start), { duration: 600 }),
  make('text-over-silence', [...lecture({ to: 280, seed: 14 }), { start: 400, end: 430, text: 'Thank you for watching, please subscribe to the channel.' }], { duration: 600, speech: [{ start: 0, end: 280 }], pieces: piecesFor(600, [300]) }),
];
await writeFile(new URL('../shared/fixtures/quality-cases.json', import.meta.url), `${JSON.stringify({ about: 'Generated by scripts/make-quality-cases.mjs. Synthetic text only.', cases }, null, 1)}\n`);
console.log(cases.map(c => `${c.name}: ${c.expected.status} ${c.expected.kinds.join(',')}`).join('\n'));
